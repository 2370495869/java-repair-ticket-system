CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(190) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(80) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_role CHECK (role IN ('CUSTOMER', 'SUPPORT', 'TECHNICIAN'))
);

CREATE TABLE repair_ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number VARCHAR(32) NOT NULL,
    customer_id BIGINT NOT NULL REFERENCES app_user (id),
    assigned_technician_id BIGINT REFERENCES app_user (id),
    title VARCHAR(120) NOT NULL,
    category VARCHAR(30) NOT NULL,
    description VARCHAR(1800) NOT NULL,
    contact_name VARCHAR(80) NOT NULL,
    contact_phone VARCHAR(20) NOT NULL,
    service_address VARCHAR(300) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_repair_ticket_number UNIQUE (ticket_number),
    CONSTRAINT ck_repair_ticket_status CHECK (status IN (
        'SUBMITTED', 'ASSIGNED', 'IN_PROGRESS', 'WAITING_FOR_CUSTOMER',
        'WAITING_FOR_PARTS', 'RESOLVED', 'CLOSED'
    ))
);

CREATE INDEX ix_repair_ticket_customer_updated ON repair_ticket (customer_id, updated_at);
CREATE INDEX ix_repair_ticket_technician_updated ON repair_ticket (assigned_technician_id, updated_at);
CREATE INDEX ix_repair_ticket_status_updated ON repair_ticket (status, updated_at);

CREATE TABLE ticket_comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES repair_ticket (id),
    author_id BIGINT NOT NULL REFERENCES app_user (id),
    body VARCHAR(1500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_ticket_comment_ticket_created ON ticket_comment (ticket_id, created_at);

CREATE TABLE ticket_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES repair_ticket (id),
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES app_user (id),
    note VARCHAR(500) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_ticket_history_ticket_changed ON ticket_status_history (ticket_id, changed_at);
